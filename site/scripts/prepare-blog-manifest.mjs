import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const entriesDirectory = join(
  process.cwd(),
  "app",
  "(blog)",
  "blog",
  "(entries)",
);
const manifestPath = join(
  process.cwd(),
  "app",
  "(blog)",
  "components",
  "blog-entry-manifest.ts",
);

function getDirectories(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);
}

const groups = getDirectories(entriesDirectory)
  .map((directory) => {
    const match = directory.match(/^\((\d+)_([^)]+)\)$/);
    if (!match) {
      throw new Error(
        `Blog entry directory ${directory} must use (NN_slug) naming.`,
      );
    }

    const order = Number(match[1]);
    const groupPath = join(entriesDirectory, directory);
    const publicDirectories = getDirectories(groupPath).filter((candidate) =>
      existsSync(join(groupPath, candidate, "page.tsx")),
    );

    if (publicDirectories.length !== 1) {
      throw new Error(
        `${directory} must contain exactly one public slug directory with page.tsx.`,
      );
    }

    const publicSlug = publicDirectories[0];
    const pagePath = join(groupPath, publicSlug, "page.tsx");
    let importPath = relative(join(process.cwd(), "app", "(blog)", "components"), pagePath)
      .split(sep)
      .join("/")
      .replace(/\.tsx$/, "");
    if (!importPath.startsWith(".")) {
      importPath = `./${importPath}`;
    }

    return { directory, importPath, order };
  })
  .sort((a, b) => a.order - b.order);

const seenOrders = new Set();
for (const group of groups) {
  if (seenOrders.has(group.order)) {
    throw new Error(`Duplicate field note order: ${group.order}.`);
  }
  seenOrders.add(group.order);
}

const imports = groups
  .map(
    ({ importPath, order }) =>
      `import { post as post${String(order).padStart(2, "0")} } from "${importPath}";`,
  )
  .join("\n");
const entries = groups
  .map(
    ({ directory, order }) =>
      `  { directory: ${JSON.stringify(directory)}, post: post${String(order).padStart(2, "0")} },`,
  )
  .join("\n");

const manifest = `/* This file is generated by scripts/prepare-blog-manifest.mjs. */
${imports}

export const blogEntries = [
${entries}
] as const;
`;

writeFileSync(manifestPath, manifest, "utf8");
console.log(`Prepared ${groups.length} blog entr${groups.length === 1 ? "y" : "ies"}.`);
